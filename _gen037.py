lines.append('        [StructLayout(LayoutKind.Sequential)] internal struct PROCESS_INFORMATION { public IntPtr p; public IntPtr t; public uint pid; public uint tid; }')
lines.append('        [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]')
lines.append('        internal struct MODULEENTRY32W { public uint dwSize; public uint mid; public uint pid; public uint g; public uint pc; public IntPtr b; public uint s; public IntPtr h; [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 256)] public string nm; [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 260)] public string pth; }')
lines.append('    }')
lines.append('    internal static class PathRoot {')
lines.append('        public static string Find() {')
lines.append('            var d = new DirectoryInfo(AppDomain.CurrentDomain.BaseDirectory);')
lines.append('            while (d != null) {')
lines.append('                if (File.Exists(Path.Combine(d.FullName, "COD OL", "codoMP_client_shipRetail.exe"))) return d.FullName;')
lines.append('                d = d.Parent;')
lines.append('            }')
lines.append('            return ".";')
lines.append('        }')
lines.append('    }')
lines.append('    class Program {')
lines.append('        const uint PAGE_RW = 0x04;')
lines.append('        const uint PAGE_RWX = 0x40;')
lines.append('        const uint MEM_COMMIT = 0x1000;')
lines.append('        const uint MEM_RESERVE = 0x2000;')
lines.append('        const uint GRMII_RVA = 0x1C80;')
lines.append('        const uint GRM_RVA = 0x1BC0;')
lines.append('        const uint TABLE_BASE = 0x00E83B00;')
lines.append('        static string Hex(uint v) { return "0x" + v.ToString("X8"); }')
lines.append('        static void Main(string[] args) {')
lines.append('            string root = PathRoot.Find();')
lines.append('            string gameDir = Path.Combine(root, "COD OL");')
lines.append('            string exe = Path.Combine(gameDir, "codoMP_client_shipRetail.exe");')
lines.append('            var sw = Stopwatch.StartNew();')
lines.append('            var si = new Native.STARTUPINFO(); si.cb = Marshal.SizeOf(typeof(Native.STARTUPINFO));')
lines.append('            Native.PROCESS_INFORMATION pi;')
lines.append('            string cmd = "\\"" + exe + "\\" -q";')
lines.append('            if (!Native.CreateProcessW(exe, cmd, IntPtr.Zero, IntPtr.Zero, false, 0, IntPtr.Zero, gameDir, ref si, out pi)) { Console.WriteLine("CREATE_FAIL"); return; }')
lines.append('            uint pid = pi.pid;')
lines.append('            Console.WriteLine("ICH-037 - PID " + pid);')
lines.append('            IntPtr proc = Native.OpenProcess(0x1F0FFF, false, pid);')
lines.append('            if (proc == IntPtr.Zero) { Console.WriteLine("OPEN_FAIL"); return; }')
lines.append('            var events = new List<string>();')
lines.append('            var mods = new HashSet<string>(StringComparer.OrdinalIgnoreCase);')
lines.append('            bool iipsLoaded = false, injected = false, gateCrossed = false;')
lines.append('            uint iipsBase = 0, rmBase = 0;')
lines.append('            var deadline = DateTime.UtcNow.AddSeconds(30);')
lines.append('            int prevModCount = 0;')
lines.append('            while (DateTime.UtcNow < deadline) {')
lines.append('                uint ec; Native.GetExitCodeProcess(pi.p, out ec);')
lines.append('                if (ec != 259) break;')
lines.append('                double t = sw.Elapsed.TotalSeconds;')
lines.append('                var snap = Native.CreateToolhelp32Snapshot(0x18, pid);')
lines.append('                if (snap != new IntPtr(-1)) {')
lines.append('                    var me = new Native.MODULEENTRY32W(); me.dwSize = (uint)Marshal.SizeOf(typeof(Native.MODULEENTRY32W));')
lines.append('                    bool ok = Native.Module32FirstW(snap, ref me);')
lines.append('                    while (ok) {')
lines.append('                        if (!mods.Contains(me.nm)) {')
lines.append('                            mods.Add(me.nm);')
lines.append('                            if (me.nm.Equals("iips.dll", StringComparison.OrdinalIgnoreCase)) { iipsLoaded = true; iipsBase = (uint)me.b; }')
lines.append('                        }')
lines.append('                        ok = Native.Module32NextW(snap, ref me);')
lines.append('                    }')
lines.append('                    Native.CloseHandle(snap);')
lines.append('                }')
lines.append('                if (iipsLoaded && !injected) {')
lines.append('                    injected = true;')
lines.append('                    var stubAddrs = new uint[48];')
lines.append('                    for (int i = 0; i < 48; i++) {')
lines.append('                        IntPtr sa = Native.VirtualAllocEx(proc, IntPtr.Zero, (IntPtr)16, MEM_COMMIT|MEM_RESERVE, PAGE_RWX);')
lines.append('                        byte[] code = (i == 2) ? new byte[] { 0xB8, 0x01, 0x00, 0x00, 0x00, 0xC3 } : new byte[] { 0x33, 0xC0, 0xC3 };')
lines.append('                        IntPtr w; Native.WriteProcessMemory(proc, sa, code, code.Length, out w);')
lines.append('                        stubAddrs[i] = (uint)sa;')
lines.append('                    }')
lines.append('                    IntPtr nvt1 = Native.VirtualAllocEx(proc, IntPtr.Zero, (IntPtr)64, MEM_COMMIT|MEM_RESERVE, PAGE_RW);')
lines.append('                    var nv1 = new byte[48];')
lines.append('                    for (int i = 0; i < 12; i++) { if (i == 2) BitConverter.GetBytes(stubAddrs[2]).CopyTo(nv1, i*4); else BitConverter.GetBytes(stubAddrs[0]).CopyTo(nv1, i*4); }')
lines.append('                    IntPtr w3; Native.WriteProcessMemory(proc, nvt1, nv1, 48, out w3);')
lines.append('                    IntPtr nvt2 = Native.VirtualAllocEx(proc, IntPtr.Zero, (IntPtr)48, MEM_COMMIT|MEM_RESERVE, PAGE_RW);')
lines.append('                    var nv2 = new byte[32];')
lines.append('                    for (int i = 0; i < 8; i++) { if (i == 0) BitConverter.GetBytes(stubAddrs[1]).CopyTo(nv2, i*4); else BitConverter.GetBytes(stubAddrs[0]).CopyTo(nv2, i*4); }')
lines.append('                    IntPtr w4; Native.WriteProcessMemory(proc, nvt2, nv2, 32, out w4);')
lines.append('                    IntPtr nvt3 = Native.VirtualAllocEx(proc, IntPtr.Zero, (IntPtr)32, MEM_COMMIT|MEM_RESERVE, PAGE_RW);')
lines.append('                    var nv3 = new byte[16];')
lines.append('                    for (int i = 0; i < 4; i++) BitConverter.GetBytes(stubAddrs[3]).CopyTo(nv3, i*4);')
lines.append('                    IntPtr w5; Native.WriteProcessMemory(proc, nvt3, nv3, 16, out w5);')
lines.append('                    IntPtr rvt = Native.VirtualAllocEx(proc, IntPtr.Zero, (IntPtr)256, MEM_COMMIT|MEM_RESERVE, PAGE_RW);')
lines.append('                    var rvtD = new byte[192];')
lines.append('                    for (int i = 0; i < 48; i++) BitConverter.GetBytes(stubAddrs[i]).CopyTo(rvtD, i*4);')
lines.append('                    IntPtr w6; Native.WriteProcessMemory(proc, rvt, rvtD, 192, out w6);')
lines.append('                    IntPtr rm = Native.VirtualAllocEx(proc, IntPtr.Zero, (IntPtr)0x420, MEM_COMMIT|MEM_RESERVE, PAGE_RW);')
lines.append('                    rmBase = (uint)rm;')
lines.append('                    var rmD = new byte[0x410];')
lines.append('                    BitConverter.GetBytes((uint)rvt).CopyTo(rmD, 0);')
lines.append('                    Encoding.ASCII.GetBytes("LocalRM_v3").CopyTo(rmD, 4);')
lines.append('                    BitConverter.GetBytes((uint)nvt1).CopyTo(rmD, 0x70);')
lines.append('                    BitConverter.GetBytes((uint)nvt2).CopyTo(rmD, 0x74);')
lines.append('                    BitConverter.GetBytes(0xFFFFFFFFu).CopyTo(rmD, 0x78);')
lines.append('                    BitConverter.GetBytes((uint)nvt3).CopyTo(rmD, 0xB4);')
lines.append('                    BitConverter.GetBytes(stubAddrs[2]).CopyTo(rmD, 0x104);')
lines.append('                    IntPtr w7; Native.WriteProcessMemory(proc, rm, rmD, 0x410, out w7);')
lines.append('                    byte[] patch = new byte[6]; patch[0] = 0xB8;')
lines.append('                    BitConverter.GetBytes(rmBase).CopyTo(patch, 1); patch[5] = 0xC3;')
lines.append('                    IntPtr w8, w9;')
lines.append('                    Native.WriteProcessMemory(proc, new IntPtr(unchecked((int)(iipsBase+GRMII_RVA))), patch, 6, out w8);')
lines.append('                    Native.WriteProcessMemory(proc, new IntPtr(unchecked((int)(iipsBase+GRM_RVA))), patch, 6, out w9);')
lines.append('                    Native.FlushInstructionCache(proc, new IntPtr(unchecked((int)(iipsBase+GRMII_RVA))), (IntPtr)6);')
lines.append('                    events.Add(t.ToString("F3") + "|RM_V3|ptr=" + Hex(rmBase));')
lines.append('                    Console.WriteLine("[" + t.ToString("F3") + "s] RM v3 injected: " + Hex(rmBase));')
lines.append('                }')
lines.append('                if (injected) {')
lines.append('                    var fb = new byte[4]; IntPtr rF;')
lines.append('                    if (Native.ReadProcessMemory(proc, new IntPtr(unchecked((int)(rmBase+0x3BC))), fb, 4, out rF)) {')
lines.append('                        uint flag = BitConverter.ToUInt32(fb, 0);')
lines.append('                        if (flag != 0 && !events.Any(e => e.Contains("FLAG_NONZERO"))) { events.Add(t.ToString("F3") + "|FLAG_NONZERO|" + flag); Console.WriteLine("[" + t.ToString("F3") + "s] FLAG=" + flag); }')
lines.append('                    }')
lines.append('                    var tb = new byte[0x300]; IntPtr rD;')
lines.append('                    if (Native.ReadProcessMemory(proc, new IntPtr(unchecked((int)TABLE_BASE)), tb, 0x300, out rD)) {')
lines.append('                        int nz = 0; for (int i = 0; i < 0x300; i += 4) if (BitConverter.ToUInt32(tb, i) != 0) nz++;')
lines.append('                        if (nz > 0 && !gateCrossed) { gateCrossed = true; events.Add(t.ToString("F3") + "|GATE|" + nz); Console.WriteLine("[" + t.ToString("F3") + "s] GATE (" + nz + ")"); }')
lines.append('                    }')
lines.append('                }')
lines.append('                if (mods.Count != prevModCount) { if (prevModCount > 0 && gateCrossed) events.Add(t.ToString("F3") + "|MODS|" + mods.Count); prevModCount = mods.Count; }')
lines.append('                if (t > 15.0 && gateCrossed && !events.Any(e => e.Contains("SURVIVED"))) { events.Add(t.ToString("F3") + "|SURVIVED"); Console.WriteLine("[" + t.ToString("F3") + "s] SURVIVED"); }')
lines.append('                Thread.Sleep(50);')
lines.append('            }')
lines.append('            uint ecF; Native.GetExitCodeProcess(pi.p, out ecF);')
lines.append('            bool exited = ecF != 259; if (!exited) Native.TerminateProcess(pi.p, 0);')
lines.append('            Native.CloseHandle(proc); Native.CloseHandle(pi.p);')
lines.append('            Console.WriteLine("\\nExited:" + exited + " after " + sw.Elapsed.TotalSeconds.ToString("F1") + "s");')
lines.append('            Console.WriteLine("Modules:" + mods.Count + " Gate:" + gateCrossed);')
lines.append('            Console.WriteLine("\\n=== Events ===");')
lines.append('            foreach (var e in events) { if (!e.Contains("MODULE") && !e.Contains("THREAD")) Console.WriteLine("  " + e); }')
lines.append('            bool flagNonzero = events.Any(e => e.Contains("FLAG_NONZERO"));')
lines.append('            Console.WriteLine("\\n=== RM State ===");')
lines.append('            Console.WriteLine("  RM+0x3BC non-zero: " + flagNonzero);')
lines.append('            if (!flagNonzero) {')
lines.append('                Console.WriteLine("  CONCLUSION: Engine did NOT call RM vtable methods");')
lines.append('                Console.WriteLine("  Engine is in WAITING state");')
lines.append('            }')
lines.append('            var csv = new StringBuilder(); csv.AppendLine("timestamp,event,detail");')
lines.append('            foreach (var e in events) { var p = e.Split("|"); while (p.Length < 3) Array.Resize(ref p, p.Length+1); csv.AppendLine(p[0] + "," + p[1] + "," + (p.Length > 2 ? p[2] : "")); }')
lines.append('            File.WriteAllText(Path.Combine(root, "ICH037_RM_CALL_TRACE.csv"), csv.ToString(), Encoding.UTF8);')
lines.append('        }')
lines.append('    }')
lines.append('}')

os.makedirs('_ich037_observer', exist_ok=True)

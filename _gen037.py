lines.append('')
lines.append('namespace ICH037 {')
lines.append('    internal static class Native {')
lines.append('        [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]')
lines.append('        internal static extern bool CreateProcessW(string app, string cmd, IntPtr pa, IntPtr ta, bool inherit, uint flags, IntPtr env, string cwd, ref STARTUPINFO si, out PROCESS_INFORMATION pi);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern IntPtr OpenProcess(uint access, bool inherit, uint pid);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern bool ReadProcessMemory(IntPtr p, IntPtr addr, byte[] buf, int size, out IntPtr read);')

lines.append('        internal static extern bool WriteProcessMemory(IntPtr p, IntPtr addr, byte[] buf, int size, out IntPtr written);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern IntPtr VirtualAllocEx(IntPtr p, IntPtr addr, IntPtr size, uint type, uint protect);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern bool CloseHandle(IntPtr h);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern bool TerminateProcess(IntPtr p, uint code);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern bool GetExitCodeProcess(IntPtr p, out uint code);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern IntPtr CreateToolhelp32Snapshot(uint flags, uint pid);')
lines.append('        [DllImport("kernel32.dll", SetLastError = true)]')
lines.append('        internal static extern bool Module32FirstW(IntPtr snap, ref MODULEENTRY32W me);')

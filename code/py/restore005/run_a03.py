sg, pg = secmap(GEN)
do = open(ORIG, 'rb').read()
dg = open(GEN, 'rb').read()

def r2o(secs, rva):
    for n, va, vs, rs, rp in secs:
        if va <= rva < va + max(vs, rs):
            if rva - va < rs:
                return rp + (rva - va)
    return None


def secmap(path):
    pe = pefile.PE(path, fast_load=True)
    return [(s.Name.rstrip(b'\x00').decode('latin1'), s.VirtualAddress,
             s.Misc_VirtualSize, s.SizeOfRawData, s.PointerToRawData) for s in pe.sections], pe


#!/usr/bin/env python3
"""Generate the opt-in BO1 Factory reference topology.

The generated table is not presented as recovered CODOL data.  Exact node
crosswalks keep their CODOL indices; BO1 nodes without an exact CODOL identity
become shadow nodes appended after the 1,100 CODOL nodes.  Negotiation links are
excluded because their CODOL animation/direction ownership has not been proven.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import struct


def bits(value: float) -> int:
    return struct.unpack("<I", struct.pack("<f", float(value)))[0]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--graph", type=pathlib.Path, required=True)
    parser.add_argument("--crosswalk", type=pathlib.Path, required=True)
    parser.add_argument("--height-overrides", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()

    graph = json.loads(args.graph.read_text(encoding="utf-8"))
    crosswalk = json.loads(args.crosswalk.read_text(encoding="utf-8"))
    node_count = int(graph["nodeCount"])
    nodes = graph["nodes"][:node_count]
    rows = crosswalk["rows"]
    if node_count != 1118 or len(nodes) != node_count or len(rows) != 1100:
        raise SystemExit("unexpected Factory identity")

    height_overrides: dict[int, float] = {}
    if args.height_overrides:
        measured = json.loads(args.height_overrides.read_text(encoding="utf-8"))
        if (measured.get("schema") !=
                "codol-bo1-hybrid-walkable-height-overrides-v1"):
            raise SystemExit("unexpected height override schema")
        if measured.get("map") != "zm_factory_sh":
            raise SystemExit("height override map mismatch")
        for row in measured["rows"]:
            index = int(row["bo1Node"])
            value = float(row["adjustedAuthoredZ"])
            if index in height_overrides or not 0 <= index < node_count:
                raise SystemExit(f"invalid duplicate height override {index}")
            if value < float(nodes[index]["origin"][2]):
                raise SystemExit(f"height override lowers BO1 node {index}")
            height_overrides[index] = value

    bo1_to_runtime: dict[int, int] = {}
    for codol_index, row in enumerate(rows):
        # The crosswalk's role/XY/yaw identity is enough to compare topology, but
        # it is not enough to reuse a CODOL node as a BO1 coordinate.  Two Factory
        # stair-foot markers (BO1 553/569) deliberately retain 45-unit Z
        # differences in the frozen audit and are explicitly excluded from
        # coordinate-transfer claims.  Keep them as donor shadow nodes so live
        # grounding starts from the donor marker instead of silently substituting
        # the other game's stair level.
        coordinate_qualified = abs(float(row.get("originZDifference", 0.0))) <= 0.01
        if row.get("eligibleNodeCrosswalk") and coordinate_qualified:
            bo1_index = int(row["bo1Node"])
            if bo1_index in bo1_to_runtime:
                raise SystemExit(f"duplicate BO1 mapping {bo1_index}")
            bo1_to_runtime[bo1_index] = codol_index

    overlap = sorted(set(height_overrides) & set(bo1_to_runtime))
    if overlap:
        raise SystemExit(
            f"height overrides may target only BO1 shadow nodes: {overlap}")

    shadow = [index for index in range(len(nodes)) if index not in bo1_to_runtime]
    for offset, bo1_index in enumerate(shadow):
        bo1_to_runtime[bo1_index] = len(rows) + offset

    walk_pairs: set[tuple[int, int]] = set()
    negotiation_pairs: set[tuple[int, int]] = set()
    for node in nodes:
        source = int(node["index"])
        for link in node["links"]:
            target = int(link["target"])
            pair = tuple(sorted((source, target)))
            if source == target:
                continue
            if link.get("negotiationLink"):
                negotiation_pairs.add(pair)
            else:
                walk_pairs.add(pair)
    walk_pairs -= negotiation_pairs

    runtime_pairs = sorted({
        tuple(sorted((bo1_to_runtime[a], bo1_to_runtime[b])))
        for a, b in walk_pairs
    })

    out: list[str] = [
        "// GENERATED by tools/reverse/GenerateBo1HybridNavgraph.py -- DO NOT EDIT.",
        "// BO1 Der Riese is a donor reference, not recovered CODOL aipaths.",
        "// The runtime admits each ordinary walk only after exact CODOL Factory",
        "// identity, live grounding, and actor-sized corridor validation.",
        f"// {len(shadow)} BO1-only shadow nodes; {len(runtime_pairs)} ordinary walk candidates.",
        f"// {len(height_overrides)} shadow heights raised from measured CODOL walkable samples.",
        "",
        '#include "sv_zm_navgraph_mp.hpp"',
        "",
        "namespace CodolGameServer",
        "{",
        "    namespace",
        "    {",
        "        constexpr std::uint32_t zm_factory_bo1_shadow_nodes[] = {",
    ]
    values = [
        bits(height_overrides.get(index, float(axis)) if axis_index == 2 else axis)
        for index in shadow
        for axis_index, axis in enumerate(nodes[index]["origin"])
    ]
    for at in range(0, len(values), 6):
        out.append("            " + ", ".join(f"0x{value:08X}" for value in values[at:at+6]) + ",")
    out.extend([
        "        };",
        "",
        "        constexpr SvZmNavEdge zm_factory_bo1_walks[] = {",
    ])
    for a, b in runtime_pairs:
        out.append(f'            {{ {a:5d}, {b:5d}, SvZmNavVia::Walk, "", "" }},')
    out.extend([
        "        };",
        "    }",
        "",
        "    const SvZmNavReferenceTable *SV_ZmBo1ReferenceTable(const std::string_view mapName)",
        "    {",
        "        static constexpr SvZmNavReferenceTable table{",
        '            "zm_factory_sh", zm_factory_bo1_shadow_nodes, zm_factory_bo1_walks};',
        "        return mapName == table.mapName ? &table : nullptr;",
        "    }",
        "}",
        "",
    ])
    args.output.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(json.dumps({
        "codolNodes": len(rows),
        "exactCrosswalk": len(nodes) - len(shadow),
        "shadowNodes": len(shadow),
        "walkCandidates": len(runtime_pairs),
        "excludedNegotiationPairs": len(negotiation_pairs),
        "measuredHeightOverrides": len(height_overrides),
    }, indent=2))


if __name__ == "__main__":
    main()

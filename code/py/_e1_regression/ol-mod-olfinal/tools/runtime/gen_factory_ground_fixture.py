"""Generate test-only ground heights from the native Factory probe report."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('report',type=Path)
parser.add_argument('output',type=Path)
args = parser.parse_args()
raw = args.report.read_bytes()
report = json.loads(raw)
assert report['map']=='zm_factory_sh' and report['built']['native_ground']
assert report['built']['coordinate_decoder']=='absolute-entity-v1'
assert len(report['nodes'])==1100
values=[]
for node in report['nodes']:
    ground = node['groundOrigin']
    if ground is None:
        values.append('std::numeric_limits<float>::quiet_NaN()')
    else:
        assert ground[:2]==node['origin'][:2]
        value = format(ground[2],'.9g')
        if '.' not in value and 'e' not in value.lower():
            value += '.0'
        values.append(value+'f')
lines = ['#pragma once','#include <array>','#include <limits>',
    '// Generated by tools/runtime/gen_factory_ground_fixture.py; tests only.',
    '// Native ground probes, not a claim of body-sweep clearance.',
    '// Input SHA256: '+hashlib.sha256(raw).hexdigest(),
    'namespace FactoryGroundFixture {',
    'inline constexpr std::array<float,1100> Heights{']
lines += ['    '+', '.join(values[i:i+6])+',' for i in range(0,len(values),6)]
lines += ['};','}']
args.output.parent.mkdir(parents=True,exist_ok=True)
args.output.write_text('\n'.join(lines)+'\n')
print(f'Generated {len(values)} test heights, {sum("NaN" in v for v in values)} unavailable')

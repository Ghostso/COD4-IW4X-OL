"""Compile a validated Factory room export into reviewed C++ data, not live code.

No game process is opened. Live floor/capsule checks remain mandatory at map load.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def compile_room(source, output):
    spec = importlib.util.spec_from_file_location('validator', HERE / 'validate-export.py')
    validator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(validator)
    data = source.read_bytes()
    if len(data) > 8_000_000:
        raise ValueError('Export exceeds size limit')
    graph = json.loads(data)
    validator.validate(graph, json.loads((HERE / 'room-v2-base.json').read_text(encoding='utf-8')))
    bindings = json.loads((HERE / 'factory-room-bindings.json').read_text(encoding='utf-8'))
    used = {end for edge in graph['edges'] for end in edge['ends']}
    nodes = [node for node in graph['nodes'] if node['id'] in used]
    index = {node['id']: i for i, node in enumerate(nodes)}
    if not nodes or len(nodes) + bindings['baseNodeCount'] >= 65535:
        raise ValueError('Unsupported node count')
    if any(len(edge['path']) != 2 for edge in graph['edges']):
        raise ValueError('Subdivide curved corridors into explicit nodes before compiling')
    ports = []
    for native, local in bindings['ports']:
        if local not in index or not 0 <= native < bindings['baseNodeCount']:
            raise ValueError('Missing or invalid required port: ' + str((native, local)))
        ports.append((native, index[local]))
    replaced = bindings['replacedOrdinaryNodes']
    if len(set(replaced)) != len(replaced) or any(not 0 <= n < bindings['baseNodeCount'] for n in replaced):
        raise ValueError('Invalid replacement manifest')
    edges = [(index[e['ends'][0]], index[e['ends'][1]]) for e in graph['edges']]
    seen = {ports[2][1]}
    while True:
        before = len(seen)
        for a, b in edges:
            if a in seen or b in seen:
                seen.update((a, b))
        if len(seen) == before:
            break
    if len(seen) != len(nodes):
        raise ValueError('Authored graph is disconnected from the door port')
    lines = ['// GENERATED by tools/navgraph/compile-room.py. Authored data; live admission required.',
             '#pragma once', '#include <array>', '#include <cstdint>',
             'namespace CodolGameServer::FactoryRoomDraft {',
             f'inline constexpr char SourceSha[]="{hashlib.sha256(data).hexdigest()}";',
             'inline constexpr std::array<float,3> Points[] = {']
    lines += ['{' + ','.join(f'{v:.6f}f' for v in n['p']) + '}, // ' + n['id'] for n in nodes]
    lines += ['};', 'inline constexpr std::uint16_t LocalIds[] = {' + ','.join(n['id'].split(':')[1] for n in nodes) + '};', 'inline constexpr std::array<std::uint16_t,2> Links[] = {']
    lines += [f'{{{a},{b}}},' for a, b in edges]
    lines += ['};', 'inline constexpr std::uint16_t Replaced[] = {' + ','.join(map(str, replaced)) + '};',
              'inline constexpr std::array<std::uint16_t,2> Ports[] = {']
    lines += [f'{{{a},{b}}},' for a, b in ports] + ['};', '}']
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return dict(nodes=len(nodes), edges=len(edges), omittedUnconnectedNodes=[n['id'] for n in graph['nodes'] if n['id'] not in used],
                sourceSha256=hashlib.sha256(data).hexdigest(), runtimeAdmission='PENDING')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('export', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(compile_room(args.export, args.output), indent=2))

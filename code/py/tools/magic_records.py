A = 0xD692ADAB
B = 0x8D51E398


def dump(name, hx):
    b = bytes.fromhex(hx)
    print("\n########## %s len=%d ##########" % (name, len(b)))
    good, els, why = G.parse(b)
    print("parse good=%s why=%s elements=%d" % (good, why, len(els)))
    if not good:
        return
    for i, (t, v) in enumerate(els):
        if isinstance(v, bytes) and len(v) in (1, 2, 4, 8):
            iv = int.from_bytes(v, "little", signed=(t == 0x07))
            u = int.from_bytes(v, "little")
            note = ""
            if u == A: note = " <<< MAGIC A query criterion"
            elif u == B: note = " <<< MAGIC B"
            print("  #%02d 0x%02x signed=%d 0x%X%s" % (i, t, iv, u, note))
        elif isinstance(v, bytes):
            esc = v.decode("latin1", "replace").encode("unicode_escape").decode()
            print("  #%02d 0x%02x len=%d %s" % (i, t, len(v), esc[:50]))
        else:
            print("  #%02d 0x%02x %r" % (i, t, v))


dump("REC_GOLDEN 258B (21/5 session record)", REC)

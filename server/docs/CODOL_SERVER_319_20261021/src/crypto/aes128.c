static const uint8_t rcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36};

void codol_aes128_init(codol_aes128_ctx_t *c, const uint8_t key[16])
{
    int i;
    for (i = 0; i < 4; i++)
        c->rk[i] = ((uint32_t)key[i*4] << 24) | ((uint32_t)key[i*4+1] << 16)
                 | ((uint32_t)key[i*4+2] << 8) | (uint32_t)key[i*4+3];
    for (i = 4; i < 44; i++) {
        uint32_t t = c->rk[i-1];
        if (i % 4 == 0) {
            t = (t << 8) | (t >> 24);
            t = ((uint32_t)sbox[(t >> 24) & 0xFF] << 24)
              | ((uint32_t)sbox[(t >> 16) & 0xFF] << 16)
              | ((uint32_t)sbox[(t >> 8) & 0xFF] << 8)
              | ((uint32_t)sbox[t & 0xFF]);
            t ^= ((uint32_t)rcon[i/4] << 24);
        }
        c->rk[i] = c->rk[i-4] ^ t;
    }
}

static void add_round_key(uint8_t st[16], const uint32_t *rk)
{
    int i;
    for (i = 0; i < 4; i++) {
        st[i*4]   ^= (uint8_t)(rk[i] >> 24);
        st[i*4+1] ^= (uint8_t)(rk[i] >> 16);
        st[i*4+2] ^= (uint8_t)(rk[i] >> 8);
        st[i*4+3] ^= (uint8_t)(rk[i]);
    }
}

static void sub_bytes(uint8_t st[16])
{
    int i;
    for (i = 0; i < 16; i++) st[i] = sbox[st[i]];
}
static uint8_t gmul2(uint8_t x)
{
    return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1B : 0x00));
}

static void mix_columns(uint8_t st[16])
{
    int c;
    for (c = 0; c < 4; c++) {
        uint8_t *p = st + c*4;
        uint8_t a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        uint8_t b0 = gmul2(a0), b1 = gmul2(a1), b2 = gmul2(a2), b3 = gmul2(a3);
        p[0] = (uint8_t)(b0 ^ (a1 ^ b1) ^ a2 ^ a3);
        p[1] = (uint8_t)(a0 ^ b1 ^ (a2 ^ b2) ^ a3);
        p[2] = (uint8_t)(a0 ^ a1 ^ b2 ^ (a3 ^ b3));
        p[3] = (uint8_t)((a0 ^ b0) ^ a1 ^ a2 ^ b3);
    }
}
static void shift_rows(uint8_t st[16])
{
    uint8_t t;
    /* 状态按列存: st[c*4 + r] ; 行 r 左移 r */
    t = st[1]; st[1] = st[5]; st[5] = st[9]; st[9] = st[13]; st[13] = t;
    t = st[2]; st[2] = st[10]; st[10] = t; t = st[6]; st[6] = st[14]; st[14] = t;
    t = st[15]; st[15] = st[11]; st[11] = st[7]; st[7] = st[3]; st[3] = t;
}

void codol_aes128_encrypt_block(const codol_aes128_ctx_t *c,
                                const uint8_t in[16], uint8_t out[16])
{
    uint8_t st[16];
    int round;
    memcpy(st, in, 16);
    add_round_key(st, c->rk);
    for (round = 1; round <= 10; round++) {
        sub_bytes(st);
        shift_rows(st);
        if (round != 10) mix_columns(st);
        add_round_key(st, c->rk + round*4);
    }
    memcpy(out, st, 16);
}

void codol_keystream_xor(const uint8_t key16[16], const uint8_t seed[6],
                         const uint8_t *in, size_t len, uint8_t *out)
{
    codol_aes128_ctx_t c;
    uint8_t counter[20], blk[16];
    size_t off;
    int i;

    codol_aes128_init(&c, key16);
    codol_sha1(seed, 6, counter);

    for (off = 0; off < len; off += 16) {
        size_t n = (len - off < 16) ? (len - off) : 16;
        codol_aes128_encrypt_block(&c, counter, blk);
        for (i = 0; i < (int)n; i++) out[off + i] = (uint8_t)(in[off + i] ^ blk[i]);
        /* 20 字节计数器按小端加 1 */
        for (i = 0; i < 20; i++) { counter[i] = (uint8_t)(counter[i] + 1); if (counter[i]) break; }
    }
}

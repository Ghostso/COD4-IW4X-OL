inline std::pair<SvNativeTrajectory,SvNativeTrajectory> SV_FactoryPowerPose(
    const SvFactoryPowerPiece &p,unsigned epoch,unsigned now) {
 SvNativeTrajectory pos{0,0,0,p.origin,{}},ang{0,0,0,p.raised,{}};
 if(!p.phases.empty()) {
  const auto *phase=&p.phases.front();
  // CODREF(1649370): phase.time is the native trajectory start; v.at
  // is only the first received snapshot. Delivery delay is not a motion pause.
  for(const auto &v:p.phases) {
   const auto start=static_cast<unsigned>(p.brush==169 || p.brush==170
       ? v.angles.time : v.position.time);
   if(start>now-epoch)break;
   phase=&v;
  }
  pos=phase->position;ang=phase->angles;pos.time+=epoch;ang.time+=epoch;
 }
 return {pos,ang};
}

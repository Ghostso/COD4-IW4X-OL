local campaign_weapon_indexes = {}
local current_campaign_weapons = nil

local function campaign_weapon_index(recorded_index)
    if recorded_index == 0 then
        return 0
    end
    local definition = campaign_weapon_definitions[recorded_index]
    if definition == nil then
        return recorded_index
    end
    local resolved = campaign_weapon_indexes[recorded_index]
    if resolved ~= nil then
        return resolved
    end
    local message, code
    resolved, message, code = codol.call("function:weaponindex", definition)
    if type(resolved) ~= "number" then
        print(
            "wetwork weapon mapping failed", recorded_index,
            definition, message, code)
        return nil
    end
    campaign_weapon_indexes[recorded_index] = resolved
    print("wetwork weapon mapped", recorded_index, resolved, definition)
    return resolved
end

local function set_campaign_weapons(
        player, primary, secondary, selected, supplemental)
    local mapped_primary = campaign_weapon_index(primary)
    local mapped_secondary = campaign_weapon_index(secondary)
    local mapped_selected = campaign_weapon_index(selected)
    local mapped_supplemental = supplemental ~= nil and
        campaign_weapon_index(supplemental) or nil
    if mapped_primary == nil or mapped_secondary == nil or
        mapped_selected == nil or
        (supplemental ~= nil and mapped_supplemental == nil) then
        return false
    end

    local _, message, code
    if mapped_supplemental ~= nil then
        _, message, code = codol.call(
            "method:setplayerweapons", player,
            mapped_primary, mapped_secondary,
            mapped_supplemental, mapped_selected)
    else
        _, message, code = codol.call(
            "method:setplayerweapons", player,
            mapped_primary, mapped_secondary, mapped_selected)
    end
    if message ~= nil then
        print("wetwork arsenal replacement failed", message, code)
        return false
    end
    current_campaign_weapons = {
        primary, secondary, selected, supplemental,
    }
    return true
end

local function set_campaign_weapon_ammo(player, weapon, clip, reserve)
    local mapped_weapon = campaign_weapon_index(weapon)
    if mapped_weapon == nil then
        return false
    end
    local _, message, code = codol.call(
        "method:setplayerweaponammo", player, mapped_weapon, clip, reserve)
    if message ~= nil then
        print("wetwork campaign ammo failed", weapon, mapped_weapon, message, code)
        return false
    end
    return true
end

local function select_campaign_weapon(player, weapon)
    local mapped_weapon = campaign_weapon_index(weapon)
    if current_campaign_weapons == nil or mapped_weapon == nil then
        return false
    end
    current_campaign_weapons[3] = weapon
    return send_command(player, "a " .. tostring(mapped_weapon))
end


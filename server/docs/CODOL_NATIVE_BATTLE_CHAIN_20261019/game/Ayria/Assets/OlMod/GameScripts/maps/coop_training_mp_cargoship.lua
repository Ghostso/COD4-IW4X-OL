local function play_map_animation(targetname, animation)
    local found = entities(targetname, "targetname")
    if #found == 0 then
        print("wetwork animated model missing", targetname, animation)
        return false
    end
    for _, entity in ipairs(found) do
        local _, message, code = codol.call(
            "method:playanimation", entity, animation, 3)
        if message ~= nil then
            print(
                "wetwork model animation failed",
                targetname, animation, message, code)
            return false
        end
    end
    return true
end


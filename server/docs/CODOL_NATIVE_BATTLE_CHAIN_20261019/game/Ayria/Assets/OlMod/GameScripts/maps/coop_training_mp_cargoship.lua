            local pitch = from[2] + (to[2] - from[2]) * fraction
            local yaw = from[3] + (to[3] - from[3]) * fraction
            local roll = from[4] + (to[4] - from[4]) * fraction
            return pitch, yaw, roll
        end
    end
    local final = intro_scripted_view_track[#intro_scripted_view_track]
    return final[2], final[3], final[4]
end

local function run_intro_flight(player)
    -- CODREF(demo 10950..182350): retail holds the client at the map's lone
    -- info_player_start_so for 3.85 seconds, links it to the insertion flight
    -- for 167.15 seconds, clears the link flags on landing, and restores
    -- ordinary movement 400 ms later. The 500 ms keys below are decoded
    -- playerState origins; 100 ms interpolation matches the dedicated tick.
    local spawn_origin = codol.call("method:getorigin", player)
    -- There is no checkpoint before the landing frame. Retail owns the player
    -- through this linked sequence, so hostile traces must not strand a death
    -- respawn outside the still-running flight thread.
    codol.call("method:setcandamage", player, false)
    if type(spawn_origin) ~= "table" or
        not set_scripted_position(
            player, spawn_origin[1], spawn_origin[2], spawn_origin[3], 5, 2048) then
        codol.call("method:setcandamage", player, true)
        return
    end
    codol.wait(3850)
    -- CODREF(demo 14800): these are asserted on the first linked flight
    -- frame, not when the player entity is created at 10950. In particular,
    -- hiding the gameplay HUD early leaves the 3.85-second cinematic wait in
    -- a different client state from retail.
    send_command(player, "s solo_play \"1\"")
    send_command(player, "n 1.000000 400")
    send_command(player, "s 490 \"55\"")
    send_command(player, "m 0")
    send_command(player, "l cargoship_intro_music_02 1.00")
    set_campaign_weapons(player, 1198, 1197, 0, 1203)
    set_campaign_weapon_ammo(player, 1198, 30, 90)
    set_campaign_weapon_ammo(player, 1197, 15, 45)
    set_campaign_weapon_ammo(player, 1203, 300, 0)
    select_campaign_weapon(player, 1203)
    -- Demo playerState fields 90/91/119/120. A zero clamp range makes the
    -- client accept fire input but reject every mouse-angle change.
    set_scripted_view_clamp(player, 10.0, 180.0, 30.0, 75.0)
    intro_vehicle_targets_active = true
    send_command(player, "s cg_miniMapHide \"1\"")
    send_command(player, "s cg_weaponBarHide \"1\"")
    send_command(player, "s pve_set_activated_info \"\"")

    -- CODREF(demo entity 510, 14800..227400): the insertion Blackhawk is a
    -- separate helicopter from the lead AI dropper.  Its measured yaw track and
    -- local camera offset keep the cabin aligned through the entire turn, then
    -- leave the aircraft hovering when the player starts the rope descent.
    local helicopter_model = "vehicle_blackhawk_hero_sas_night"
    local first = intro_player_path[1]
    local first_helicopter_x, first_helicopter_y,
        first_helicopter_z, first_helicopter_yaw =
        intro_helicopter_transform(0, first[2], first[3], first[4])
    local insertion_helicopter = spawn_presentation_model(
        helicopter_model,
        first_helicopter_x,
        first_helicopter_y,
        first_helicopter_z,
        first_helicopter_yaw)
    local squad_restored = false

    for index = 1, #intro_player_path - 1 do
        local from = intro_player_path[index]
        local to = intro_player_path[index + 1]
        local duration = to[1] - from[1]
        local elapsed = 0
        while elapsed < duration do
            local path_elapsed = from[1] + elapsed
            local fraction = elapsed / duration
            local player_x = from[2] + (to[2] - from[2]) * fraction
            local player_y = from[3] + (to[3] - from[3]) * fraction
            local player_z = from[4] + (to[4] - from[4]) * fraction
            local helicopter_x, helicopter_y,
                helicopter_z, helicopter_yaw =
                intro_helicopter_transform(
                    path_elapsed, player_x, player_y, player_z)
            local pm_flags = 184549376
            if path_elapsed >= 161850 then
                pm_flags = 2048
            end
            if not set_scripted_position(
                    player,
                    player_x, player_y, player_z,
                    1, pm_flags) then
                clear_scripted_position(player)
                if insertion_helicopter ~= nil then
                    codol.call("method:delete", insertion_helicopter)
                end
                codol.call("method:setcandamage", player, true)
                return
            end
            -- CODREF(demo playerState field 91): yaw clamp base follows the
            -- insertion helicopter's authored yaw plus the camera's 270-degree
            -- local seat offset. Keeping this at the 180-degree first-frame
            -- value makes the client's mouse fight a stale world-space clamp
            -- while the aircraft turns.
            local clamp_yaw = (helicopter_yaw + 270.0) % 360.0
            local clamp_pitch_range = path_elapsed >= 157450 and 35.0 or 30.0
            local clamp_yaw_range = path_elapsed >= 157450 and 70.0 or 75.0
            set_scripted_view_clamp(
                player, 10.0, clamp_yaw, clamp_pitch_range, clamp_yaw_range)
            if path_elapsed >= 157450 then
                -- The final turn widens pitch slightly and narrows yaw before
                -- retail takes the camera onto its measured descent track.
                local pitch, yaw, roll = intro_scripted_view(path_elapsed)
                set_scripted_view_angles(player, pitch, yaw, roll)
                set_scripted_link_state(
                    player, path_elapsed >= 161850 and 1 or 0,
                    pitch, yaw, roll)
            end
            if insertion_helicopter ~= nil then
                if not set_presentation_model(
                        insertion_helicopter, helicopter_model,
                        helicopter_x, helicopter_y,
                        helicopter_z, helicopter_yaw) then
                    insertion_helicopter = nil
                else
                    move_intro_occupants(
                        helicopter_x, helicopter_y, helicopter_z,
                        helicopter_yaw, path_elapsed)
                end
            end
            if not squad_restored and path_elapsed >= 113850 then
                restore_intro_squad_to_deck()
                squad_restored = true
            end
            local wait_time = math.min(100, duration - elapsed)
            codol.wait(wait_time)
            elapsed = elapsed + wait_time
        end
    end

    local landing = intro_player_path[#intro_player_path]
    set_scripted_position(
        player, landing[2], landing[3], landing[4], 1, 0)
    local final_pitch, final_yaw, final_roll = intro_scripted_view(landing[1])
    set_scripted_view_angles(player, final_pitch, final_yaw, final_roll)
    set_scripted_link_state(
        player, 0, final_pitch, final_yaw, final_roll)
    intro_vehicle_targets_active = false
    if clear_vehicle_targets ~= nil then
        clear_vehicle_targets()
    end
    if insertion_helicopter ~= nil then
        local helicopter_x, helicopter_y,
            helicopter_z, helicopter_yaw =
            intro_helicopter_transform(
                landing[1], landing[2], landing[3], landing[4])
        set_presentation_model(
            insertion_helicopter, helicopter_model,
            helicopter_x, helicopter_y, helicopter_z, helicopter_yaw)
    end
    codol.wait(400)
    clear_scripted_position(player)
    codol.call("method:setcandamage", player, true)

    if insertion_helicopter ~= nil then
        -- The recorded helicopter remains on the landed path through the
        -- hallway approach and is removed at 227400, 45.45 seconds after the
        -- player's 181950 landing frame.
        local landed_helicopter = insertion_helicopter
        assert(codol.thread(function()
            codol.wait(45450)
            codol.call("method:delete", landed_helicopter)
        end))
    end
end


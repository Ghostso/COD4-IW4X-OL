local function interpolate_intro_helicopter_yaw(elapsed)
    local first = intro_helicopter_yaw_path[1]
    if elapsed <= first[1] then
        return first[2]
    end
    for index = 1, #intro_helicopter_yaw_path - 1 do
        local from = intro_helicopter_yaw_path[index]
        local to = intro_helicopter_yaw_path[index + 1]
        if elapsed <= to[1] then
            local fraction = (elapsed - from[1]) / (to[1] - from[1])
            local delta = ((to[2] - from[2] + 180.0) % 360.0) - 180.0
            return from[2] + delta * fraction
        end
    end
    return intro_helicopter_yaw_path[#intro_helicopter_yaw_path][2]
end

local function intro_helicopter_transform(elapsed, player_x, player_y, player_z)
    -- At 175200 (160400 ms after the linked flight begins), retail leaves the
    -- aircraft hovering while the player completes the rope descent.
    if elapsed >= 160400 then
        return -1702.853, -209.375, 920.502, -119.092
    end

    local yaw = interpolate_intro_helicopter_yaw(elapsed)
    local radians = math.rad(yaw)
    local local_x = 20.439
    local local_y = 56.178
    local helicopter_x = player_x +
        math.cos(radians) * local_x - math.sin(radians) * local_y
    local helicopter_y = player_y +
        math.sin(radians) * local_x + math.cos(radians) * local_y
    return helicopter_x, helicopter_y, player_z + 131.109, yaw
end


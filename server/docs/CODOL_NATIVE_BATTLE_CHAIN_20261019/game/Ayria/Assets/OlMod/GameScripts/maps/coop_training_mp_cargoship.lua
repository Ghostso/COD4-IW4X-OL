        codol.wait(900)
        delete_targetname("cargohold1_door")
    elseif phase_name == "cargohold_open" then
        wait_for_started_groups_clear({
            "cargohold_runners", "cargohold1_flashed_enemies",
            "cargohold2_catwalk_enemies",
            "cargohold2_catwalk_enemiesa",
            "cargohold2_catwalk_enemies2", "cargohold_runners2",
            "explode_combat_enemies", "cargohold3_enemies1",
            "cargohold3_enemies2", "cargohold3_enemies3",
        })
        run_cargo_interaction(player)
    elseif phase_name == "sinking" then
        -- The force-explosion brush is crossed at 362350; the recorded blast
        -- and music begin at 362950. Retail deliberately leaves the nine
        -- explode_combat actors alive here; the detonation retires them.
        codol.wait(600)
        delete_targetname("escape_door")
        assert(codol.thread(run_sinking_enemy_blast))
        assert(codol.thread(function()
            run_sinking_presentation(player)
        end))
        assert(codol.thread(run_sinking_exploder_track))
        assert(codol.thread(run_sinking_earthquake_track))
        assert(codol.thread(run_sinking_physics_explosion_track))
        assert(codol.thread(function()
            run_sinking_ground_tilt_track(player)
        end))
    elseif phase_name == "escape_hull_break" then
        -- MapEnts binds this panel directly to the first hull-break brush.
        -- The animation name is the panel's own authored `animation` field.
        play_map_animation("hullpanel01", "iu_hull_breach_panel_01")
    elseif phase_name == "escape_hull_break_second" then
        -- The second brush opens the remaining two panels as the player moves
        -- aft through the ruptured lower deck.
        play_map_animation("hullpanel01a", "iu_hull_breach_panel_01")
        play_map_animation("hullpanel02", "iu_hull_breach_panel_02")
    elseif phase_name == "escape_lower_hall" then
        assert(codol.thread(function()
            run_extraction_helicopter()
        end))
    elseif phase_name == "extraction_jump" then
        -- CODREF(demo 440250..475600): touching escape_player_jump transfers
        -- the player to the extraction sequence, but mission success does not
        -- appear until the 35.35-second helicopter departure has completed.
        -- The concurrent sinking presentation owns the recorded ambient clear
        -- and finale music inside this hold.
        codol.call("method:setcandamage", player, false)
        run_extraction_flight(player)
    end
end

local function finish_mission(player)
    -- MEASURED: success UI begins at 475600, the server decides the mission at
    -- 480850, and EXE_MATCHENDED follows at 481850. This 5250 ms hold belongs
    -- to Wetwork; the generic campaign end owner supplies the final one second.
    codol.call("method:setcandamage", player, false)
    send_command(player, "n 0.010000 2000")
    send_command(player, "s ui_match_complete \"1\"")
    send_command(player, "s ui_mission_success \"1\"")
    send_command(player, "s ui_skip_mission_success \"1\"")
    codol.wait(850)
    send_command(player, "i 3000 6.000000 0 1")
    codol.wait(4400)
    local _, message, code = codol.call("function:finishmission")
    if message ~= nil then
        print("wetwork mission completion failed", message, code)
    end
end

local function run_route(player)
    print("wetwork mission route started", #route)
    for index, entry in ipairs(route) do
        if #entry.triggers == 0 then
            print("wetwork mission trigger missing", entry.name)
            return
        else
            while not touches_any(entry.triggers, player) do
                codol.wait(50)
            end
        end
        mission_phase = index
        print("wetwork mission phase", index, entry.name)
        apply_phase_presentation(player, entry.name)
        local _, checkpoint_message, checkpoint_code = codol.call(
            "method:savecheckpoint", player)
        if checkpoint_message ~= nil then
            print(
                "wetwork checkpoint failed", entry.name,
                checkpoint_message, checkpoint_code)
        end
        -- Always yield at a boundary. Adjacent and overlapping volumes must not
        -- collapse into several phase changes in one server frame.
        codol.wait(0)
    end
    print("wetwork mission route complete", mission_phase)
    finish_mission(player)
end

local function run_escape_death_volume(player, targetname)
    local triggers = entities(targetname, "targetname")
    if #triggers == 0 then
        print("wetwork escape death trigger missing", targetname)
        return
    end

    -- CODREF(MapEnts): these three brushes are named explicitly as flood/fall
    -- death volumes and become relevant only after force_explosion_start. A
    -- single MOD_TRIGGER_HURT transaction enters the ordinary campaign death
    -- and checkpoint-respawn path. Re-arm only after the new life has left the
    -- brush so one touch cannot enqueue several deaths.
    while mission_phase < 9 do
        codol.wait(50)
    end
    while true do
        if touches_any(triggers, player) then
            send_command(player, "n 0.010000 500")
            local _, message, code = codol.call(
                "method:finishplayerdamage", player,
                nil, nil, 1000, 0, 16, 165,
                nil, { 0, 0, 1 }, 0, 0, 0)
            if message ~= nil then
                print(
                    "wetwork escape death failed", targetname,
                    message, code)
            end
            repeat
                codol.wait(100)
            until not touches_any(triggers, player)
        else
            codol.wait(50)
        end
    end
end

assert(codol.on("player_killed", function(killed_player, event)
    if mission_started ~= true or killed_player == nil then
        return
    end
    -- The generic coop gametype deliberately owns no timed respawn. Wetwork
    -- restarts this player at the last route checkpoint while leaving the
    -- encounter and mission threads alive.
    send_command(killed_player, "n 0.010000 500")
    local _, message, code = codol.call(
        "method:respawn", killed_player, 2000)
    if message ~= nil then
        print("wetwork checkpoint respawn failed", message, code)
    end
end))


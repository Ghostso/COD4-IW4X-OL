local function run_blast_knockdown(player)
    -- CODREF(demo playerState 362950..377000): the cargo explosion starts
    -- shellshock profile 9 for 14 seconds, links the player into the captured
    -- fall/recovery motion and view track for 13 seconds, changes the link
    -- flags on the final animation tick, then returns control.
    codol.call("method:setcandamage", player, false)
    set_shellshock(player, 9, 14000)

    for index = 1, #blast_knockdown_player_path - 1 do
        local from = blast_knockdown_player_path[index]
        local to = blast_knockdown_player_path[index + 1]
        local duration = to[1] - from[1]
        local elapsed = 0
        while elapsed < duration do
            local path_elapsed = from[1] + elapsed
            local fraction = elapsed / duration
            local pm_flags = 50364416
            if path_elapsed >= 12900 then
                pm_flags = 33587200
            end
            if not set_scripted_position(
                    player,
                    from[2] + (to[2] - from[2]) * fraction,
                    from[3] + (to[3] - from[3]) * fraction,
                    from[4] + (to[4] - from[4]) * fraction,
                    1, pm_flags) then
                clear_scripted_position(player)
                codol.call("method:setcandamage", player, true)
                return false
            end
            local pitch, yaw, roll = blast_view_angles(path_elapsed)
            if not set_scripted_view_angles(player, pitch, yaw, roll) then
                clear_scripted_position(player)
                codol.call("method:setcandamage", player, true)
                return false
            end
            local wait_time = math.min(100, duration - elapsed)
            codol.wait(wait_time)
            elapsed = elapsed + wait_time
        end
    end

    local final = blast_knockdown_player_path[#blast_knockdown_player_path]
    set_scripted_position(
        player, final[2], final[3], final[4], 1, 33587200)
    local final_pitch, final_yaw, final_roll = blast_view_angles(final[1])
    set_scripted_view_angles(
        player, final_pitch, final_yaw, final_roll)
    clear_scripted_position(player)
    codol.call("method:setcandamage", player, true)
    return true
end


local function run_lead_blackhawk()
    -- CODREF(MapEnt 236): the AI dropper starts at chopper_sidestart2 and
    -- follows me2_auto2879 -> 2876 -> 2875 -> 2877 -> 2880. COD4's retained
    -- vehicle path converts speed 40 MPH with 17.6 units/second per MPH.
    -- CODREF(demo 14800): the model and its six occupants first exist on the
    -- first linked-flight frame, 3.85 seconds after the player entity. Motion
    -- starts at 16700, 1.9 seconds after that model creation.
    codol.wait(3850)
    local model = "vehicle_blackhawk_hero_sas_night"
    local helicopter = spawn_presentation_model(
        model,
        lead_blackhawk_path[1][1],
        lead_blackhawk_path[1][2],
        lead_blackhawk_path[1][3],
        240.5)
    if helicopter == nil then
        return
    end

    codol.wait(1900)
    local moving_milliseconds = 0
    local elapsed_since_spawn = 1900
    local occupants_removed = false
    local speed = 40.0 * 17.6
    for index = 1, #lead_blackhawk_path - 1 do
        local from = lead_blackhawk_path[index]
        local to = lead_blackhawk_path[index + 1]
        local dx = to[1] - from[1]
        local dy = to[2] - from[2]
        local dz = to[3] - from[3]
        local duration = math.floor(
            math.sqrt(dx * dx + dy * dy + dz * dz) / speed * 1000.0 + 0.5)
        local elapsed = 0
        while elapsed < duration do
            if not occupants_removed and elapsed_since_spawn >= 22850 then
                -- CODREF(demo 37650): slots 0..5 disappear here while the
                -- lead helicopter itself continues to its crash boundary.
                remove_lead_blackhawk_occupants()
                occupants_removed = true
            end
            local fraction = elapsed / duration
            local x = from[1] + dx * fraction
            local y = from[2] + dy * fraction
            local z = from[3] + dz * fraction
            if not set_presentation_model(
                    helicopter, model, x, y, z,
                    240.5) then
                return
            end
            move_lead_blackhawk_occupants(x, y, z)
            local wait_time = math.min(100, duration - elapsed)
            if not occupants_removed and
                    elapsed_since_spawn < 22850 then
                wait_time = math.min(
                    wait_time, 22850 - elapsed_since_spawn)
            end
            codol.wait(wait_time)
            elapsed = elapsed + wait_time
            moving_milliseconds = moving_milliseconds + wait_time
            elapsed_since_spawn = elapsed_since_spawn + wait_time
        end
    end
    local last = lead_blackhawk_path[#lead_blackhawk_path]
    set_presentation_model(
        helicopter, model, last[1], last[2], last[3], 240.5)

    if not occupants_removed then
        remove_lead_blackhawk_occupants()
    end

    -- CODREF(demo 46500): the crash cue and authored script_unload occur
    -- 31.7 seconds after the helicopter's 14800 creation. Keep the model
    -- through that boundary even if rounded path segments arrive early.
    local crash_hold = 29800 - moving_milliseconds
    if crash_hold > 0 then
        codol.wait(crash_hold)
    end
    codol.call("method:delete", helicopter)
end


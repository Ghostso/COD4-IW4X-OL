local function scripted_missile_call(kind, missile, entry)
    local weapon = campaign_weapon_index(entry[4])
    if weapon == nil then
        return nil, "campaign missile weapon is unavailable", 0
    end
    if missile == nil then
        return codol.call("function:" .. kind,
            weapon, entry[5], entry[6],
            entry[7], entry[8], entry[9],
            entry[10], entry[11], entry[12],
            entry[13], entry[14], entry[15], entry[16], entry[17])
    end
    return codol.call("method:" .. kind, missile,
        weapon, entry[5], entry[6],
        entry[7], entry[8], entry[9],
        entry[10], entry[11], entry[12],
        entry[13], entry[14], entry[15], entry[16], entry[17])
end

local function run_scripted_missile_track()
    local elapsed = 0
    local missiles = {}
    for _, entry in ipairs(scripted_missile_track) do
        codol.wait(entry[1] - elapsed)
        elapsed = entry[1]
        if entry[2] == 1 then
            local missile, message, code = scripted_missile_call(
                "spawnscriptedmissile", nil, entry)
            missiles[entry[3]] = missile
            if missile == nil then
                print("wetwork scripted missile spawn failed",
                    entry[3], message, code)
            end
        elseif entry[2] == 2 then
            local missile = missiles[entry[3]]
            if missile ~= nil then
                local _, message, code = scripted_missile_call(
                    "setscriptedmissile", missile, entry)
                if message ~= nil then
                    print("wetwork scripted missile update failed",
                        entry[3], message, code)
                end
            end
        else
            local missile = missiles[entry[3]]
            if missile ~= nil then
                codol.call("method:delete", missile)
                missiles[entry[3]] = nil
            end
        end
    end
end

local function trigger_exploder(index, effect_index)
    if effect_index ~= nil then
        set_config_string(11990 + index, tostring(effect_index))
    end
    local _, message, code = codol.call(
        "function:triggerexploder", index)
    if message ~= nil then
        print("wetwork exploder failed", index, message, code)
        return false
    end
    return true
end


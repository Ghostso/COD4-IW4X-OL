local function run_encounter(encounter, player)
    local group_name = encounter.group
    local trigger_value = encounter.trigger_value or group_name
    local trigger_key = encounter.trigger_key or "target"
    local triggers = entities(trigger_value, trigger_key)
    if #triggers == 0 then
        print(
            "wetwork encounter trigger missing",
            group_name, trigger_key, trigger_value)
        return
    end
    while not touches_any(triggers, player) do
        codol.wait(50)
    end
    if encounter_started[group_name] == true then
        return
    end
    local wave_offsets = repeating_enemy_wave_offsets[group_name]
    if wave_offsets == nil then
        spawn_enemy_group(group_name)
        return
    end

    encounter_pending_waves[group_name] = true
    local elapsed = 0
    for _, offset in ipairs(wave_offsets) do
        codol.wait(offset - elapsed)
        elapsed = offset
        spawn_enemy_group(group_name)
    end
    encounter_pending_waves[group_name] = nil
end

local function retire_enemy_actor(actor, entity_number, start_ragdoll)
    local slot = enemy_slot_by_entity[entity_number]

local function acquire_enemy_slot()
    while true do
        for slot = 0, 23 do
            if enemy_slot_available[slot] == true and
                    enemy_slot_in_use[slot] == nil then
                enemy_slot_in_use[slot] = true
                return slot
            end
        end
        codol.wait(50)
    end
end

local function enemy_attachment(spawner, classname)
    local spawner_number = codol.call("method:getentitynumber", spawner)
    local recorded = enemy_attachment_by_spawner[spawner_number]
    if recorded ~= nil then
        return recorded
    end
    if string.find(classname, "_rpg_", 1, true) ~= nil then
        return 463
    end
    if string.find(classname, "_ump_", 1, true) ~= nil then
        return 466
    end
    local attachment = enemy_weapon_pattern[enemy_weapon_pattern_index]
    enemy_weapon_pattern_index = enemy_weapon_pattern_index + 1
    if enemy_weapon_pattern_index > #enemy_weapon_pattern then
        enemy_weapon_pattern_index = 1
    end
    return attachment
end

local function enemy_weapon_name(classname)
    if string.find(classname, "_ump_", 1, true) ~= nil then
        return "ump45_mp"
    end
    -- Explosive projectiles remain a separate restoration pass. Until that
    -- native path is ready, RPG spawners retain their recorded third-person
    -- attachment while using the mission's ordinary rifle damage owner.
    return "ak47_mp"
end

local function squared_distance(first, second)
    if type(first) ~= "table" or type(second) ~= "table" then
        return nil
    end
    local x = second[1] - first[1]
    local y = second[2] - first[2]
    local z = second[3] - first[3]
    return x * x + y * y + z * z
end

local function run_enemy_ai(
        actor, player, entity_number, spawner_number, classname)
    -- CODREF(C-2021-7-25[22-11-33]coop.demo): ET_ACTOR asserts
    -- EV_FIRE_WEAPON 573 times. actorfire owns that exact event, a retained
    -- rifle trace, and finishPlayerDamage; this loop only owns deterministic
    -- encounter cadence and range.
    if string.find(classname, "_rpg_", 1, true) ~= nil then
        -- CODREF(demo): the only hostile RPG source poses paired with the
        -- retained missile track are spawner 152 at +2300 ms and spawner 136
        -- at +7500 ms. Their damage is already carried by ET_MISSILE; using
        -- actorfire here added a repeated hitscan rifle hit every second.
        local delay = spawner_number == 152 and 2300 or
            (spawner_number == 136 and 7500 or nil)
        if delay ~= nil then
            codol.wait(delay)
            if enemy_alive_by_entity[entity_number] == true then
                codol.call("method:actorfirepresentation", actor)
            end
        end
        return
    end

    local cadence = 850 + (spawner_number % 5) * 70
    local first_fire_delay = enemy_first_fire_delay_by_spawner[spawner_number]
    if first_fire_delay == nil then
        first_fire_delay = 250 + (spawner_number % 7) * 80
    end
    local burst_pattern = enemy_burst_pattern_by_spawner[spawner_number]
    local burst_index = 1
    codol.wait(first_fire_delay)
    while enemy_alive_by_entity[entity_number] == true do
        local actor_origin = codol.call("method:getorigin", actor)
        local player_origin = codol.call("method:getorigin", player)
        local distance = squared_distance(actor_origin, player_origin)
        if distance ~= nil and distance <= 1960000 then
            local burst_size = 1
            if burst_pattern ~= nil then
                burst_size = burst_pattern[burst_index]
                burst_index = burst_index + 1
                if burst_index > #burst_pattern then
                    burst_index = 1
                end
            end
            for _ = 1, burst_size do
                codol.call("method:actorfirepresentation", actor)
            end
            local _, message, code = codol.call(
                "method:actortracedamage", actor,
                player, 4, enemy_weapon_name(classname))
            if message ~= nil then
                print("wetwork actor fire failed", entity_number, message, code)
                return
            end
        end
        codol.wait(cadence)
    end
end

local function release_enemy_actor(actor, entity_number)
    local slot = enemy_slot_by_entity[entity_number]
    local group_name = enemy_group_by_entity[entity_number]
    release_vehicle_target(entity_number)
    enemy_slot_by_entity[entity_number] = nil
    enemy_alive_by_entity[entity_number] = nil
    enemy_group_by_entity[entity_number] = nil
    enemy_actor_by_entity[entity_number] = nil
    enemy_spawner_by_entity[entity_number] = nil
    if group_name ~= nil then
        encounter_active_count[group_name] = math.max(
            0, (encounter_active_count[group_name] or 1) - 1)
    end
    codol.call("method:delete", actor)
    if slot ~= nil then
        enemy_slot_in_use[slot] = nil
    end
end

local function run_recorded_enemy_path(actor, entity_number, spawner_number)
    local path = enemy_recorded_path_by_spawner[spawner_number]
    if path == nil or #path < 2 then
        return false
    end
    for index = 1, #path - 1 do
        local from = path[index]
        local to = path[index + 1]
        local duration = to[1] - from[1]
        local elapsed = 0
        local yaw_delta = (to[5] - from[5] + 180) % 360 - 180
        while elapsed < duration and
                enemy_alive_by_entity[entity_number] == true do
            local fraction = elapsed / duration
            local _, message, code = codol.call(
                "method:setactorposition", actor,
                from[2] + (to[2] - from[2]) * fraction,
                from[3] + (to[3] - from[3]) * fraction,
                from[4] + (to[4] - from[4]) * fraction,
                from[5] + yaw_delta * fraction)
            if message ~= nil then
                print("wetwork recorded actor motion failed",
                    entity_number, message, code)
                return true
            end
            local wait_time = math.min(100, duration - elapsed)
            codol.wait(wait_time)
            elapsed = elapsed + wait_time
        end
        if enemy_alive_by_entity[entity_number] ~= true then
            return true
        end
    end
    local final = path[#path]
    codol.call(
        "method:setactorposition", actor,
        final[2], final[3], final[4], final[5])
    return true
end

local function run_enemy_goal(actor, spawner, entity_number, spawner_number)
    -- CODREF(MapEnts): Wetwork marks advancing actors with script_forcegoal=1
    -- (and a few scripted runners with the equivalent setforcegoal command).
    -- Their target names an authored script_struct/info_volume destination.
    -- Follow that data rather than steering every hostile toward the player.
    local force_goal = codol.call(
        "method:getmapfield", spawner, "script_forcegoal")
    local parameters = codol.call(
        "method:getmapfield", spawner, "script_parameters")
    local noteworthy = codol.call(
        "method:getmapfield", spawner, "script_noteworthy")
    local group_name = enemy_group_by_entity[entity_number]
    local repeating_runner = group_name == "cargohold_runners2"
    if run_recorded_enemy_path(actor, entity_number, spawner_number) then
        if noteworthy == "delete_on_goal" and
                enemy_alive_by_entity[entity_number] == true then
            release_enemy_actor(actor, entity_number)
        end
        return
    end
    local forced_by_parameters = type(parameters) == "string" and
        string.find(parameters, "setforcegoal", 1, true) ~= nil
    if force_goal ~= "1" and not forced_by_parameters and
        noteworthy ~= "delete_on_goal" and not repeating_runner then
        return
    end

    local target_name = codol.call("method:getmapfield", spawner, "target")
    if type(target_name) ~= "string" or target_name == "" then
        return
    end
    local goal = first_entity(target_name, "targetname")
    if goal == nil then
        print("wetwork actor goal missing", entity_number, target_name)
        return
    end
    local start = codol.call("method:getorigin", actor)
    local destination = codol.call("method:getorigin", goal)
    if type(start) ~= "table" or type(destination) ~= "table" then
        return
    end

    local dx = destination[1] - start[1]
    local dy = destination[2] - start[2]
    local dz = destination[3] - start[3]
    local distance = math.sqrt(dx * dx + dy * dy + dz * dz)
    if distance < 1.0 then
        return
    end
    local yaw = math.deg(math.atan(dy, dx))
    -- COD4's default human run speed is 190 units/second.  Map pathfinding is
    -- not restored yet, so explicit force-goal spawners and the recorded cargo
    -- runners take this direct authored leg; stationary defenders stay put.
    local duration = math.max(100, math.floor(distance / 190.0 * 1000.0 + 0.5))
    local elapsed = 0
    while elapsed < duration and
            enemy_alive_by_entity[entity_number] == true do
        local fraction = elapsed / duration
        local _, message, code = codol.call(
            "method:setactorposition", actor,
            start[1] + dx * fraction,
            start[2] + dy * fraction,
            start[3] + dz * fraction,
            yaw)
        if message ~= nil then
            print("wetwork actor motion failed", entity_number, message, code)
            return
        end
        local wait_time = math.min(100, duration - elapsed)
        codol.wait(wait_time)
        elapsed = elapsed + wait_time
    end
    if enemy_alive_by_entity[entity_number] ~= true then
        return
    end
    codol.call(
        "method:setactorposition", actor,
        destination[1], destination[2], destination[3], yaw)

    -- The deck drones are authored as one-way crossing traffic.  Retail frees
    -- them at their goal so they do not consume one of the eleven hostile
    -- agent rows used by the next encounter.
    if noteworthy == "delete_on_goal" or repeating_runner then
        release_enemy_actor(actor, entity_number)
    end
end

local function spawn_enemy(spawner, group_name)
    local classname = codol.call("method:getmapfield", spawner, "classname")
    if type(classname) ~= "string" or
        string.sub(classname, 1, 12) ~= "actor_enemy_" then
        return false
    end

    local slot = acquire_enemy_slot()
    local actor, message, code = codol.call(
        "method:spawnactor", spawner, slot, 259, 1, 0, 0)
    if actor == nil then
        enemy_slot_in_use[slot] = nil
        print("wetwork enemy spawn failed", group_name, message, code)
        return false
    end
    codol.call("method:setagentfield", actor, 12, 1)
    codol.call(
        "method:setagentfield", actor, 13,
        enemy_attachment(spawner, classname))
    codol.call("method:setagentfield", actor, 23, 27)
    codol.call("method:sethealth", actor, 100)
    codol.call("method:setcandamage", actor, true)

    local entity_number = codol.call("method:getentitynumber", actor)
    if type(entity_number) ~= "number" then
        codol.call("method:delete", actor)
        enemy_slot_in_use[slot] = nil
        print("wetwork enemy missing entity number", group_name)
        return false
    end
    enemy_slot_by_entity[entity_number] = slot
    enemy_alive_by_entity[entity_number] = true
    enemy_group_by_entity[entity_number] = group_name
    enemy_actor_by_entity[entity_number] = actor
    encounter_active_count[group_name] =
        (encounter_active_count[group_name] or 0) + 1
    local spawner_number = codol.call(
        "method:getentitynumber", spawner)
    enemy_spawner_by_entity[entity_number] = spawner_number
    publish_vehicle_target(actor, entity_number, spawner)
    assert(codol.thread(function()
        run_enemy_ai(
            actor, mission_player, entity_number, spawner_number, classname)
    end))
    assert(codol.thread(function()
        run_enemy_goal(actor, spawner, entity_number, spawner_number)
    end))
    return true
end

local function spawn_enemy_group(group_name)
    local first_wave = encounter_started[group_name] ~= true
    encounter_started[group_name] = true
    encounter_spawning[group_name] = true
    if first_wave then
        encounter_active_count[group_name] = 0
    end
    local count = 0
    for _, spawner in ipairs(entities(group_name, "targetname")) do
        if spawn_enemy(spawner, group_name) then
            count = count + 1
        end
    end
    encounter_spawning[group_name] = nil
    print("wetwork enemy group spawned", group_name, count)
end

local function wait_for_started_groups_clear(group_names)
    -- Route and encounter threads can observe the same trigger in one frame.
    -- Yield once so each encounter has a chance to mark itself started before
    -- a door tests the counter.
    codol.wait(0)
    while true do
        local blocked = false
        for _, group_name in ipairs(group_names) do
            if encounter_started[group_name] == true and
                (encounter_pending_waves[group_name] == true or
                 encounter_spawning[group_name] == true or
                 (encounter_active_count[group_name] or 0) > 0) then
                blocked = true
                break
            end
        end
        if not blocked then
            return
        end
        codol.wait(100)
    end
end


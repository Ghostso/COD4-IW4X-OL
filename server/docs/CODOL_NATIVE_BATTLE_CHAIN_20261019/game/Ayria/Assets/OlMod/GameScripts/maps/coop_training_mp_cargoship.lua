local function interpolate_angle(from, to, fraction)
    local delta = (to - from + 180.0) % 360.0 - 180.0
    return from + delta * fraction
end

local function blast_view_angles(at_time)
    for index = 1, #blast_knockdown_view_path - 1 do
        local from = blast_knockdown_view_path[index]
        local to = blast_knockdown_view_path[index + 1]
        if at_time <= to[1] then
            local fraction = (at_time - from[1]) / (to[1] - from[1])
            return interpolate_angle(from[2], to[2], fraction),
                interpolate_angle(from[3], to[3], fraction),
                interpolate_angle(from[4], to[4], fraction)
        end
    end
    local final = blast_knockdown_view_path[#blast_knockdown_view_path]
    return final[2], final[3], final[4]
end


local function run_extraction_flight(player)
    -- CODREF(demo 440250..475600): retail links the player to the departing
    -- CH-46 for the full 35.35-second extraction. These player origins are
    -- decoded directly from that interval; driving both the player and vehicle
    -- from one track keeps the first-person camera inside the aircraft instead
    -- of leaving an invulnerable player falling below a static presentation
    -- model. pm_flags change at 440750 and 455550 in the recorded playerState.
    local helicopter_model = "vehicle_ch46e"
    local helicopter_offset = { 657.765, 154.675, 427.559 }

    for index = 1, #extraction_player_path - 1 do
        local from = extraction_player_path[index]
        local to = extraction_player_path[index + 1]
        local duration = to[1] - from[1]
        local elapsed = 0
        while elapsed < duration do
            local mission_elapsed = from[1] + elapsed
            local fraction = elapsed / duration
            local player_x = from[2] + (to[2] - from[2]) * fraction
            local player_y = from[3] + (to[3] - from[3]) * fraction
            local player_z = from[4] + (to[4] - from[4]) * fraction
            local pm_flags = 33818624
            if mission_elapsed >= 15300 then
                pm_flags = 33589248
            elseif mission_elapsed >= 500 then
                pm_flags = 33556480
            end

            if not set_scripted_position(
                    player, player_x, player_y, player_z, 1, pm_flags) then
                -- Preserve the retail success boundary even if a disappearing
                -- player object prevents the visual track from completing.
                codol.wait(35350 - mission_elapsed)
                return false
            end
            if extraction_helicopter ~= nil and
                not set_presentation_model(
                    extraction_helicopter, helicopter_model,
                    player_x + helicopter_offset[1],
                    player_y + helicopter_offset[2],
                    player_z + helicopter_offset[3], 120.0) then
                extraction_helicopter = nil
            end

            local wait_time = math.min(100, duration - elapsed)
            codol.wait(wait_time)
            elapsed = elapsed + wait_time
        end
    end

    local final = extraction_player_path[#extraction_player_path]
    set_scripted_position(
        player, final[2], final[3], final[4], 1, 33589248)
    if extraction_helicopter ~= nil then
        set_presentation_model(
            extraction_helicopter, helicopter_model,
            final[2] + helicopter_offset[1],
            final[3] + helicopter_offset[2],
            final[4] + helicopter_offset[3], 120.0)
    end
    return true
end


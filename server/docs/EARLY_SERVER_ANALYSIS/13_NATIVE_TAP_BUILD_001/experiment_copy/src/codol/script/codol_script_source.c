#include <string.h>
#include <errno.h>

static codol_script_fs_reader_t fs_reader;
void CODOL_SetScriptFsReader(codol_script_fs_reader_t reader) { fs_reader=reader; }
/* A root spelled "fs:<dir>" reads <dir>/<prefix><name> through the host's
 * search path -- the server's own archive, main/sh1x_svr_scripts.iwd -- with
 * exactly the validation applied to a loose file. */
static int read_fs_source(const char *root,const char *prefix,const char *name,char **out,size_t *length)
{
    char path[4096],*data=NULL; size_t size=0; int written,status;
    if(!fs_reader) return 0;
    written=*root ? snprintf(path,sizeof(path),"%s/%s%s",root,prefix,name) : snprintf(path,sizeof(path),"%s%s",prefix,name);
    if(written<0 || (size_t)written>=sizeof(path)) return -1;
    status=fs_reader(path,&data,&size);
    if(status!=1) { free(data); return status<0 ? -1 : 0; }
    if(!data || size>16*1024*1024 || memchr(data,0,size)) { free(data); return -1; }
    data[size]=0; *out=data; *length=size; return 1;
}
static int read_source(const char *root,const char *prefix,const char *name,char **out,size_t *length)
{
    char path[4096],*data; long size; FILE *file; int written;
    if(!root || !*root) return 0;
    if(!strncmp(root,"fs:",3)) return read_fs_source(root+3,prefix,name,out,length);
    written=snprintf(path,sizeof(path),"%s/%s%s",root,prefix,name);
    if(written<0 || (size_t)written>=sizeof(path)) return -1;
    /* Case-insensitive on POSIX hosts, as Windows and C1 resolve these names. */
    file=CODOL_FOpenReadCaseless(path);
    if(!file) return errno==ENOENT ? 0 : -1;
    if(fseek(file,0,SEEK_END) || (size=ftell(file))<0 || size>16*1024*1024 || fseek(file,0,SEEK_SET)) {
        fclose(file); return -1;
    }
    data=malloc((size_t)size+1);
    if(!data) { fclose(file); return -1; }
    if(fread(data,1,(size_t)size,file)!=(size_t)size || ferror(file)) {
        fclose(file); free(data); return -1;
    }
    if(fclose(file) || memchr(data,0,(size_t)size)) { free(data); return -1; }
    data[size]=0; *out=data; *length=(size_t)size; return 1;
}
static int read_reference(const char *root,const char *prefix,const char *name,char **out,size_t *length)
{
    static const char damaged[]="// THIS FILE IS AUTOGENERATED, DO NOT MODIFY\n\n"
        "main().{..a[0] = \"head_militia_a_wht\";..return a;.}";
    static const char seal_damaged[]="// THIS FILE IS AUTOGENERATED, DO NOT MODIFY\n\n"
        "main().{..a[0] = \"head_seal_soccom_da\";..return a;.}";
    int status=read_source(root,prefix,name,out,length);size_t i;
    /* Exact alpha0022 export corruption: periods substituted for whitespace.
     * Preserve byte/line positions. Never rewrite overlays or unknown bodies. */
    if(status==1 &&
       ((!strcmp(name,"xmodelalias/alias_opforce_militia_heads_wht.gsc") &&
         *length==sizeof(damaged)-1 && !memcmp(*out,damaged,sizeof(damaged)-1)) ||
        (!strcmp(name,"xmodelalias/alias_seal_soccom_heads_mp_blk.gsc") &&
         *length==sizeof(seal_damaged)-1 && !memcmp(*out,seal_damaged,sizeof(seal_damaged)-1))))
        for(i=0;i<*length;++i)if((*out)[i]=='.')(*out)[i]=' ';
    return status;
}
/* A CoDOL asset category ("mp", "coop", "zm") names a subdirectory of the
 * native overlay. Only lowercase ASCII, short enough that the prefix cannot
 * push a legal script name past the path buffer, so the same traversal rules
 * that guard `name` hold for the prefix without re-validating a joined path. */
static int zone_type_prefix(const char *zone_type,char *out,size_t capacity)
{
    size_t i;
    if(!zone_type || !*zone_type) return 0;
    for(i=0;zone_type[i];++i)
        if(i+2>=capacity || zone_type[i]<'a' || zone_type[i]>'z') return 0;
    memcpy(out,zone_type,i); out[i]='/'; out[i+1]=0;
    return 1;
}
int CODOL_ReadScriptSourceWithNativeOverlayForZone(const char *base,const char *overlay,
    const char *native_overlay,const char *zone_type,const char *name,char **out,size_t *length)
{
    const char *segment,*p; char prefix[16]; int status;
    if(!name || !*name || !out || !length) return -1;
    segment=name;
    for(p=name;;++p) {
        if(*p=='\\' || *p==':' || (unsigned char)*p>=128) return -1;
        if(!*p || *p=='/') {
            size_t n=(size_t)(p-segment);
            if(!n || (n==1 && segment[0]=='.') || (n==2 && segment[0]=='.' && segment[1]=='.')) return -1;
            if(!*p) break;
            segment=p+1;
        }
    }
    /* The native adaptations are written against this VM and its builtins, so
     * they take precedence over the alpha0022 overlay, which targets the Python
     * VM (for example its _perkfunctions.gsc omits functions vendor scripts
     * link against). The user overlay still overrides the vendor sources. */
    /* A coop or zm match must not compile a single multiplayer gametype,
     * callback or level script, and the reverse holds just as strictly: the
     * scripts differ per asset category, not per map. Give each category its
     * own root above the shared one, so the same module name
     * (maps/mp/gametypes/_callbacksetup) resolves to that category's file.
     * "mp" has no directory of its own today, so this probe misses and the
     * multiplayer order below is exactly what it was. */
    if(zone_type_prefix(zone_type,prefix,sizeof(prefix))) {
        status=read_source(native_overlay,prefix,name,out,length); if(status) return status;
    }
    status=read_source(native_overlay,"",name,out,length); if(status) return status;
    status=read_source(overlay,"",name,out,length); if(status) return status;
    status=read_reference(base,"mp/",name,out,length); if(status) return status;
    status=read_reference(base,"",name,out,length); if(status) return status;
    /* alpha0022's IW4 source export contains this one duplicated directory
     * prefix in a filename. Keep the script's canonical module identity and
     * prefer all correctly named sources; do not infer aliases for other names. */
    if(!strcmp(name,"character/mp_character_us_army_lmg.gsc"))
        return read_source(base,"","character/charactermp_character_us_army_lmg.gsc",out,length);
    /* This export omits mp_ from the filename, but its body selects the exact
     * mp_body_us_army_smg_b model, multiplayer head alias and viewhands. */
    if(!strcmp(name,"character/mp_character_us_army_smg_b.gsc"))
        return read_source(base,"","character/character_us_army_smg_b.gsc",out,length);
    return 0;
}
int CODOL_ReadScriptSourceWithNativeOverlay(const char *base,const char *overlay,const char *native_overlay,
    const char *name,char **out,size_t *length)
{
    return CODOL_ReadScriptSourceWithNativeOverlayForZone(base,overlay,native_overlay,NULL,name,out,length);
}
int CODOL_ReadScriptSource(const char *base,const char *overlay,const char *name,char **out,size_t *length)
{
    return CODOL_ReadScriptSourceWithNativeOverlayForZone(base,overlay,NULL,NULL,name,out,length);
}
